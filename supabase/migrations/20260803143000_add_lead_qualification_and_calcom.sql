  add constraint leads_additional_context_length check (additional_context is null or char_length(additional_context) <= 1000),
  add constraint leads_cal_booking_uid_length check (cal_booking_uid is null or char_length(cal_booking_uid) <= 255),
  add constraint leads_cal_booking_url_length check (cal_booking_url is null or char_length(cal_booking_url) <= 2048),
  add constraint leads_cal_booking_url_protocol check (cal_booking_url is null or cal_booking_url ~* '^https://'),
  add constraint leads_cal_booking_timezone_length check (cal_booking_timezone is null or char_length(cal_booking_timezone) <= 100),
  add constraint leads_callback_consistency check (callback_requested_at is null or next_action = 'callback'),
  add constraint leads_cal_created_consistency check (cal_booking_created_at is null or cal_booking_uid is not null),
  add constraint leads_cal_cancelled_consistency check (cal_booking_cancelled_at is null or cal_booking_status = 'cancelled');

