  add constraint leads_primary_growth_problem_check check (primary_growth_problem is null or primary_growth_problem in ('referral-reliance', 'inconsistent-enquiries', 'ads-underperforming', 'website-not-converting', 'poor-quality-leads', 'limited-tracking', 'other')),
