  add column capacity_status text,
  add column acquisition_source text,
  add column website_url text,
  add column decision_authority text,
  add column google_ads_status text,
  add column planned_ad_spend_range text,
  add column implementation_timing text,
  add column website_status text,
  add column primary_growth_problem text,
  add column additional_context text,
  add column next_action text,
  add column callback_preference text,
  add column callback_requested_at timestamptz,
  add column qualification_completed_at timestamptz,
  add column funnel_completed_at timestamptz,
  add column cal_booking_status text,
  add column cal_booking_uid text,
  add column cal_booking_url text,
  add column cal_booking_start_at timestamptz,
  add column cal_booking_timezone text,
  add column cal_booking_created_at timestamptz,
  add column cal_booking_cancelled_at timestamptz,
  add column cal_webhook_received_at timestamptz,
  add constraint leads_practitioner_range_check check (practitioner_range is null or practitioner_range in ('solo', '2-3', '4-6', '7-10', '11+')),
  add constraint leads_location_range_check check (location_range is null or location_range in ('1', '2', '3', '4+')),
  add constraint leads_capacity_status_check check (capacity_status is null or capacity_status in ('need-now', 'some', 'near-capacity', 'unsure')),
  add constraint leads_acquisition_source_check check (acquisition_source is null or acquisition_source in ('referrals', 'organic-google', 'google-ads', 'meta-ads', 'partnerships', 'other')),
  add constraint leads_decision_authority_check check (decision_authority is null or decision_authority in ('owner', 'part-decision', 'researching')),
  add constraint leads_google_ads_status_check check (google_ads_status is null or google_ads_status in ('current', 'previous', 'never', 'unsure')),
  add constraint leads_planned_ad_spend_range_check check (planned_ad_spend_range is null or planned_ad_spend_range in ('under-1000', '1000-1500', '1500-3000', '3000+', 'unsure')),
